CREATE DATABASE Product_Managerment


USE Product_Managerment

CREATE TABLE BRAND (
	BRAND_ID INT NOT NULL PRIMARY KEY,
	BRAND_NAME NVARCHAR(200),
)


CREATE TABLE CATEGORY (
	CATEGORY_ID INT NOT NULL PRIMARY KEY,
	CATEGORY_NAME NVARCHAR(200)
)

CREATE TABLE PRODUCT (
	PRODUCT_ID DECIMAL(18,0) NOT NULL PRIMARY KEY,
	PRODUCT_NAME NVARCHAR(200),
	CAPACITY NVARCHAR(100),
	BRAND_ID INT,
	CATEGORY_ID INT,
	PRICE MONEY,
	CONSTRAINT PK_BRAND_ID FOREIGN KEY (BRAND_ID) REFERENCES BRAND(BRAND_ID),
	CONSTRAINT PK_CATEGORY_ID FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORY(CATEGORY_ID)
)

CREATE TABLE WAREHOUSE (
	WAREHOUSE_ID INT NOT NULL PRIMARY KEY,
	WAREHOUSE_NAME NVARCHAR(200),
	WAREHOUSE_ADDRESS NVARCHAR(200)
)

CREATE TABLE INVENTORY (
	PRODUCT_ID DECIMAL (18,0) NOT NULL,
	WAREHOUSE_ID INT NOT NULL,
	INVENTORY_QUANTITY INT,
	CONSTRAINT PR_PRODUCT_ID_WAREHOUSE PRIMARY KEY (PRODUCT_ID, WAREHOUSE_ID),
	CONSTRAINT PK_PRODUCT_ID FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(PRODUCT_ID),
	CONSTRAINT PK_WAREHOUSE_ID FOREIGN KEY (WAREHOUSE_ID) REFERENCES WAREHOUSE(WAREHOUSE_ID)
)

CREATE TABLE PROMOTION (
	PROMOTION_ID INT NOT NULL PRIMARY KEY,
	PROMOTION_NAME NVARCHAR(200),
	DATE_START DATE,
	DATE_END DATE,
	PROMOTION_TYPE NVARCHAR(200),
	PROMOTION_VALUE INT
)
 
CREATE TABLE PRODUCT_PROMOTION (
	PRODUCT_ID DECIMAL (18, 0) NOT NULL,
	PROMOTION_ID INT NOT NULL,
	CONSTRAINT PR_PRODUCT_ID_PROMOTION_ID PRIMARY KEY (PRODUCT_ID, PROMOTION_ID),
	CONSTRAINT PK_PRODUCT_ID1 FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(PRODUCT_ID),
	CONSTRAINT PK_PROMOTION_ID FOREIGN KEY (PROMOTION_ID) REFERENCES PROMOTION(PROMOTION_ID)
)

CREATE TABLE CUSTOMER_RANK (
	RANK_ID INT NOT NULL PRIMARY KEY,
	RANK_NAME NVARCHAR(200),
	POINT INT,
	VOUCHER FLOAT
)

CREATE TABLE CUSTOMER (
	CUSTOMER_ID DECIMAL (18, 0) NOT NULL PRIMARY KEY,
	CUSTOMER_NAME NVARCHAR(200),
	CUSTOMER_PASSWORD CHAR(20),
	CUSTOMER_EMAIL CHAR(200),
	CUSTOMER_PHONE_NUMBER INT,
	CUSTOMER_ADDRESS NVARCHAR(200),
	CUSTOMER_SEX NVARCHAR(5),
	CUSTOMER_DATE DATE,
	TOTAL_POINT INT,
	RANK_ID INT,
	CONSTRAINT PK_RANK_ID FOREIGN KEY (RANK_ID) REFERENCES CUSTOMER_RANK(RANK_ID)
) 

CREATE TABLE CART (
	CART_ID INT NOT NULL PRIMARY KEY,
	CUSTOMER_ID DECIMAL (18, 0) NOT NULL,
	CONSTRAINT PK_CUSTOMER_ID FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID)
)


CREATE TABLE CART_ITEM (
	PRODUCT_ID DECIMAL (18, 0) NOT NULL,
	CART_ID INT NOT NULL,
	QUANTITY INT,
	PRICE MONEY,
	CONSTRAINT PR_CART_ITEM PRIMARY KEY (PRODUCT_ID, CART_ID),
	CONSTRAINT PK_PRODUCT_ID2 FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(PRODUCT_ID),
	CONSTRAINT PK_CART_ID FOREIGN KEY (CART_ID) REFERENCES CART(CART_ID)
)

CREATE TABLE PRODUCT_REVIEW (
	PRODUCT_ID DECIMAL (18, 0) NOT NULL,
	CUSTOMER_ID DECIMAL (18, 0) NOT NULL,
	REVIEW_CONTENT NVARCHAR(1000),
	REVIEW_DATE DATE,
	REVIEW_START INT,
	CONSTRAINT PR_PRODUCT_ID_CUSTOMER_ID PRIMARY KEY (PRODUCT_ID, CUSTOMER_ID),
	CONSTRAINT PK_PRODUCT_ID3 FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(PRODUCT_ID),
	CONSTRAINT PK_CUSTOMER_ID1 FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID)
)

CREATE TABLE EMPLOYEE (
	EMPLOYEE_ID DECIMAL (18, 0) NOT NULL PRIMARY KEY,
	EMPLOYEE_NAME NVARCHAR(200),
	EMPLOYEE_EMAIL NVARCHAR(200),
	EMPLOYEE_PHONE_NUMBER INT,
)

CREATE TABLE SHIPPING_METHOD (
	SHIPPING_ID INT NOT NULL PRIMARY KEY,
	METHOD_NAME NVARCHAR(200),
)

CREATE TABLE PAYMENT_METHOD (
	PAYMENT_ID INT NOT NULL PRIMARY KEY,
	PAYMENT_NAME NVARCHAR(200),
)

CREATE TABLE PURCHASE_ORDER (
	ORDER_ID INT NOT NULL PRIMARY KEY,
	ORDER_DATE DATE,
	CUSTOMER_ID DECIMAL (18, 0),
	CART_ID INT NOT NULL,		
	EMPLOYEE_ID DECIMAL (18, 0)NOT NULL,
	SHIPPING_ID INT NOT NULL,
	PAYMENT_ID INT NOT NULL,
	TOTAL_PRICE MONEY,
	CONSTRAINT PK_CART_ID1 FOREIGN KEY (CART_ID) REFERENCES CART(CART_ID),
	CONSTRAINT PK_CUSTOMER_ID2 FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID),
	CONSTRAINT PK_EMPLOYEE_ID FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID),
	CONSTRAINT PK_SHIPPING_ID FOREIGN KEY (SHIPPING_ID) REFERENCES SHIPPING_METHOD(SHIPPING_ID),
	CONSTRAINT PK_PAYMENT_ID FOREIGN KEY (PAYMENT_ID) REFERENCES PAYMENT_METHOD(PAYMENT_ID)
)

CREATE TABLE ORDER_DETAIL (
	ORDER_ID INT NOT NULL,
	PRODUCT_ID DECIMAL (18, 0) NOT NULL,
	PRICES MONEY,
	QUANTITY INT,
	TOTAL_PRICE MONEY,
	CONSTRAINT PR_PRODUCT_ID_ORDER_ID PRIMARY KEY (PRODUCT_ID, ORDER_ID),
	CONSTRAINT PK_PRODUCT_ID4 FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(PRODUCT_ID),
	CONSTRAINT PK_ORDER_ID FOREIGN KEY (ORDER_ID) REFERENCES PURCHASE_ORDER(ORDER_ID)
)